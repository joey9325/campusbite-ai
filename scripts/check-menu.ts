import assert from "node:assert/strict";
import { executeTool, getMenu, parsePrice, normalizeImage } from "../lib/menu.ts";
assert.equal(parsePrice("Rp20,000"), 20000);
assert.equal(parsePrice("Rp20.000"), 20000);
for (const value of ["", "tidak diketahui", "Rp20,000-30,000", "-5000"]) assert.equal(parsePrice(value), null);
assert.equal(normalizeImage("./images/ramen.jpg"), "/menu-images/ramen.jpg");
assert.equal(normalizeImage("./images/does-not-exist.jpg"), null);
const all = getMenu();
assert(all.length > 0 && all.some((menu) => menu.price === null));
const chicken = executeTool("filter_budget", { keyword: "ayam", maxBudget: 20000 });
assert(chicken.menus.length > 0 && chicken.menus.every((menu) => menu.name.toLowerCase().includes("ayam") && menu.price !== null && menu.price <= 20000));
const japanese = executeTool("filter_stall", { stall: "Japanese Food", maxBudget: 30000, inclusive: false });
assert(japanese.menus.length > 0 && japanese.menus.every((menu) => menu.stall === "Japanese Food" && menu.price !== null && menu.price < 30000));
const cheapest = executeTool("price_extreme", { order: "cheapest" });
assert(cheapest.menus.length > 0 && cheapest.menus.every((menu) => menu.price === Math.min(...all.flatMap((item) => item.price === null ? [] : [item.price]))));
assert.equal(executeTool("search_menu", { keyword: "steak wagyu", maxBudget: 10000 }).total, 0);
assert(executeTool("list_stalls", {}).stalls?.includes("Japanese Food"));
assert.equal(executeTool("compare_menu", { ids: chicken.menus.slice(0, 2).map((menu) => menu.id) }).total, 2);
assert.throws(() => executeTool("filter_budget", { maxBudget: -1 }));
assert.throws(() => executeTool("compare_menu", { ids: ["invented", "menu-1"] }));
console.log(`Menu checks passed: ${all.length} CSV rows, ${all.filter((menu) => !menu.image).length} unavailable images. All four requested scenarios verified at the tool layer.`);
